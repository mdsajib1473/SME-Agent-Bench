"""IEEE style LaTeX tables (booktabs) for the main results and the McNemar tests."""

import math

from analysis.load import arch_label, model_label

HEADER = "% Generated by analysis/run_all.py from results/{tag}. Do not edit by hand; rerun the analysis.\n"


def num(value, digits=1):
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    return f"{value:.{digits}f}"


def pct(value):
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    return f"{value * 100:.0f}"


def p_value(value):
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    if value < 0.001:
        return "$<$0.001"
    return f"{value:.3f}"


def odds(value):
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    if math.isinf(value):
        return "$\\infty$"
    return f"{value:.2f}"


def energy(value):
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    return f"{value:.3f}"


def main_table(main_df, tag, k, seeds, energy_note):
    columns = [
        ("Model", "l"), ("Architecture", "l"), ("Succ.", "r"), ("95\\% CI", "c"), (f"pass$^{{{k}}}$", "r"),
        ("Trap viol.", "r"), ("Viol.", "r"), ("Calls", "r"), ("Tok. in (k)", "r"), ("Tok. out", "r"),
        ("Wall p50", "r"), ("Wall p95", "r"), ("E/task", "r"), ("E/succ.", "r"), ("E/succ. ctr.", "r"),
    ]
    seed_text = f"{seeds} seed" + ("s" if seeds != 1 else "")
    pass_text = "with one seed this equals the success rate" if k == 1 else f"share of tasks solved in all {k} seeds"
    caption = (
        f"Main results ({seed_text} per task). Success rate, pass$^{{{k}}}$ ({pass_text}) and policy"
        " violation rate on trap tasks in percent; the 95\\%"
        " confidence interval is a bootstrap over tasks (10{,}000 resamples). Viol.: count of all policy"
        " violations. Calls: mean LLM calls per run. Tok.: mean prompt (thousands) and completion tokens."
        " Wall: median and 95th percentile of the agent run time in seconds, excluding model reset and settle"
        " wait. E/task: mean net GPU energy per run in Wh; E/succ.: total net GPU energy divided by the number"
        f" of successful runs, from sampled power (ctr.: from the NVML energy counter, as a cross check).{energy_note}"
    )
    lines = [
        HEADER.format(tag=tag),
        "\\begin{table*}[t]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        f"\\caption{{{caption}}}",
        "\\label{tab:main_results}",
        "\\begin{tabular}{" + "".join(align for _, align in columns) + "}",
        "\\toprule",
        " & ".join(name for name, _ in columns) + " \\\\",
        "\\midrule",
    ]
    previous = None
    for _, row in main_df.iterrows():
        if previous is not None and row["model"] != previous:
            lines.append("\\midrule")
        model_cell = model_label(row["model"]) if row["model"] != previous else ""
        previous = row["model"]
        cells = [
            model_cell,
            arch_label(row["arch"]),
            pct(row["success_rate"]),
            f"[{pct(row['success_ci_low'])}, {pct(row['success_ci_high'])}]",
            pct(row["pass_k"]),
            pct(row["trap_violation_rate"]),
            str(int(row["violations_total"])),
            num(row["mean_llm_calls"]),
            num(row["mean_prompt_tokens"] / 1000.0),
            num(row["mean_completion_tokens"], 0),
            num(row["wall_median_s"]),
            num(row["wall_p95_s"]),
            energy(row["mean_net_energy_wh"]),
            energy(row["energy_per_success_wh"]),
            energy(row["energy_per_success_counter_wh"]),
        ]
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


def mcnemar_table(tests_df, tag, seeds):
    vote = (
        "per task success in the single seed" if seeds == 1
        else f"per task majority vote over {seeds} seeds (a tie counts as failure)" if seeds == 2
        else f"per task majority vote over {seeds} seeds"
    )
    caption = (
        f"Exact McNemar tests on {vote}. $b$: tasks solved only by the first system, $c$: only by the second;"
        " OR $= b/c$. $p_{\\mathrm{Holm}}$ is Holm adjusted over the three architecture pairs of each model"
        " and over the model comparisons of all architectures."
    )
    lines = [
        HEADER.format(tag=tag),
        "\\begin{table}[t]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        f"\\caption{{{caption}}}",
        "\\label{tab:mcnemar}",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "Comparison & $n$ & $b$ & $c$ & OR & $p$ & $p_{\\mathrm{Holm}}$ \\\\",
    ]
    for (family, group), rows in tests_df.groupby(["family", "group"], sort=False):
        heading = (
            f"{model_label(group)}: architectures" if family == "architectures"
            else f"{arch_label(group)}: models"
        )
        lines += ["\\midrule", f"\\multicolumn{{7}}{{l}}{{\\emph{{{heading}}}}} \\\\"]
        for _, row in rows.iterrows():
            if family == "architectures":
                name = f"{arch_label(row['a'])} vs {arch_label(row['b'])}"
            else:
                name = f"{model_label(row['a'])} vs {model_label(row['b'])}"
            cells = [name, str(row["n_tasks"]), str(row["a_only"]), str(row["b_only"]), odds(row["odds_ratio"]),
                     p_value(row["p_exact"]), p_value(row["p_holm"])]
            lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)
